class_grade = (int(input("What is your grade percentage in math? ")))

if class_grade >= 90:
    print("You have an A in math!")

elif class_grade >= 80:
    print("You have an B in math!")

elif class_grade >= 70:
    print("You have an C in math!")

elif class_grade >= 60:
    print("You have an D in math!")

else:
    print("You are failing math!")